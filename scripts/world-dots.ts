/**
 * Precomputes a dotted world map (land dots on an equirectangular grid) from Natural Earth via world-atlas,
 * so the client ships ~10KB of path data instead of a geo library + topojson.
 *
 *   npx tsx scripts/world-dots.ts
 */
import { geoContains } from "d3-geo";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json") as Topology<{ land: GeometryCollection }>;
const land = feature(topo, topo.objects.land);

const STEP = 2; // degrees between dots
const LAT_MAX = 78;
const LAT_MIN = -56;
const W = 360 / STEP;
const H = (LAT_MAX - LAT_MIN) / STEP;

let d = "";
let count = 0;
// Run-length encode each row: a horizontal segment drawn with stroke-dasharray="0 1" + round caps
// renders exactly one dot per grid unit, so a whole run of land costs a few bytes.
for (let row = 0; row <= H; row++) {
  const lat = LAT_MAX - row * STEP;
  let runStart = -1;
  for (let col = 0; col <= W; col++) {
    const lng = -180 + col * STEP + STEP / 2;
    const isLand = col < W && geoContains(land, [lng, lat]);
    if (isLand) count++;
    if (isLand && runStart < 0) runStart = col;
    if (!isLand && runStart >= 0) {
      d += `M${runStart} ${row}h${col - 1 - runStart}`;
      runStart = -1;
    }
  }
}

const out = `// Generated by scripts/world-dots.ts — do not edit.
// Land dots on a ${STEP}° equirectangular grid; draw with stroke-linecap="round" and stroke-dasharray="0 1".
export const WORLD_DOTS = {
  step: ${STEP},
  latMax: ${LAT_MAX},
  latMin: ${LAT_MIN},
  width: ${W},
  height: ${H},
  path: "${d}",
} as const;
`;
writeFileSync("src/data/world-dots.ts", out);
console.log(`world-dots: ${count} dots, ${(out.length / 1024).toFixed(1)}KB`);
