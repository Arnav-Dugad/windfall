/**
 * Generates `.wrangler/seed.sql` from shared/seed/*. Deterministic (seeded PRNG), but timestamps are
 * relative to "now" so dashboards and streaks look alive whenever you seed.
 *
 *   npm run db:seed:local   |   npm run db:seed:remote
 */
import { mkdirSync, writeFileSync } from "node:fs";
import type { SeedSeeker } from "../shared/domain";
import { COMMUNITY_PATRONS, DEMO_PATRONS, DEMO_SEEKER } from "../shared/seed/personas";
import { SEED_SEEKERS } from "../shared/seed/seekers";

const DAY = 24 * 60 * 60 * 1000;
const NOW = Date.now();

// mulberry32 — tiny deterministic PRNG
let state = 0x5eed1e55;
function rand() {
  state |= 0;
  state = (state + 0x6d2b79f5) | 0;
  let t = Math.imul(state ^ (state >>> 15), 1 | state);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const pick = <T>(xs: readonly T[]) => xs[Math.floor(rand() * xs.length)]!;

const q = (v: string | number | boolean | null | undefined): string => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "1" : "0";
  if (typeof v === "number") return String(Math.round(v * 1e6) / 1e6);
  return `'${v.replace(/'/g, "''")}'`;
};
const insert = (table: string, row: Record<string, string | number | boolean | null | undefined>) =>
  `INSERT INTO ${table} (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(q).join(", ")});`;

const sql: string[] = [
  "-- Generated by scripts/seed.ts. All people, stories and gifts are fictional demo data.",
  ...["ledger_entries", "balances", "gifts", "swipes", "reports", "documents", "request_updates", "requests", "users"].map(
    (t) => `DELETE FROM ${t};`,
  ),
];

// ---- Users -----------------------------------------------------------------
const allPatrons = [
  ...DEMO_PATRONS.map((p) => ({ id: p.id, displayName: p.displayName, anon: p.anonymousByDefault, persona: p.persona })),
  ...COMMUNITY_PATRONS.map((p) => ({ id: p.id, displayName: p.displayName, anon: p.anonymousByDefault, persona: null })),
];
for (const p of allPatrons) {
  sql.push(
    insert("users", {
      id: p.id,
      role: "patron",
      display_name: p.displayName,
      persona: p.persona,
      avatar_seed: p.id,
      anonymous_by_default: p.anon,
      is_demo: true,
      created_at: NOW - 200 * DAY,
    }),
  );
}

type Seeded = SeedSeeker & { userId: string; requestId: string; fullyFund?: boolean };
const seekers: Seeded[] = [
  { ...DEMO_SEEKER },
  ...SEED_SEEKERS.map((s) => ({ ...s, userId: `usr_sk_${s.slug}`, requestId: `req_${s.slug}` })),
];

// A few modest requests are seeded as already cleared, so "debts cleared" has history.
const clearable = seekers
  .slice(1)
  .filter((s) => s.fundedRatio > 0.2 && s.fundedRatio < 0.85)
  .sort((a, b) => goalOf(a) - goalOf(b))
  .slice(0, 4);
for (const s of clearable) s.fullyFund = true;

function goalOf(s: SeedSeeker) {
  return s.breakdown.reduce((sum, b) => sum + b.amountCents, 0);
}

for (const s of seekers) {
  sql.push(
    insert("users", {
      id: s.userId,
      role: "seeker",
      display_name: s.firstName,
      persona: s === seekers[0] ? "maya" : null,
      avatar_seed: s.userId,
      anonymous_by_default: false,
      is_demo: true,
      created_at: NOW - (s.postedDaysAgo + 3) * DAY,
    }),
  );
}

// ---- Requests, gifts, ledger -------------------------------------------------
const demoWeights = DEMO_PATRONS.map((p) => p.history.gifts);
const balances = new Map<string, number>();
const addBalance = (acct: string, d: number) => balances.set(acct, (balances.get(acct) ?? 0) + d);
const demoGiftLog = new Map<string, { giftId: string; requestCreated: number }[]>();
const giftRows: Record<string, string | number | boolean | null>[] = [];
let giftSeq = 0;

function weightedDemoPatron() {
  const total = demoWeights.reduce((a, b) => a + b, 0);
  let r = rand() * total;
  for (let i = 0; i < DEMO_PATRONS.length; i++) {
    r -= demoWeights[i]!;
    if (r <= 0) return DEMO_PATRONS[i]!;
  }
  return DEMO_PATRONS[0]!;
}

for (const s of seekers) {
  const goal = goalOf(s);
  const createdAt = NOW - s.postedDaysAgo * DAY - Math.floor(rand() * 8) * 60 * 60 * 1000;
  const ratio = s.fullyFund ? 1 : s.fundedRatio;
  const target = s.fullyFund ? goal : Math.floor((goal * ratio) / 10_000) * 10_000; // to the $100

  // Split the target into a handful of gifts from distinct patrons.
  const amounts: number[] = [];
  if (target > 0) {
    const n = Math.max(1, Math.min(10, Math.round(target / 350_000) + Math.floor(rand() * 3)));
    const weights = Array.from({ length: n }, () => 0.4 + rand());
    const wsum = weights.reduce((a, b) => a + b, 0);
    let left = target;
    for (let i = 0; i < n - 1; i++) {
      const a = Math.max(10_000, Math.floor((target * weights[i]!) / wsum / 10_000) * 10_000);
      if (a >= left) break;
      amounts.push(a);
      left -= a;
    }
    amounts.push(left);
  }

  const used = new Set<string>();
  let funded = 0;
  amounts.forEach((amount, i) => {
    const isLast = i === amounts.length - 1;
    let patronId: string;
    let anon: boolean;
    if (s.fullyFund && isLast) {
      patronId = "usr_demo_theo"; // Theo loves clearing a debt to zero
      anon = false;
    } else {
      let p = rand() < 0.62 ? weightedDemoPatron() : null;
      let candidate = p ? p.id : pick(COMMUNITY_PATRONS).id;
      for (let tries = 0; used.has(candidate) && tries < 10; tries++) {
        p = rand() < 0.5 ? weightedDemoPatron() : null;
        candidate = p ? p.id : pick(COMMUNITY_PATRONS).id;
      }
      patronId = candidate;
      anon = allPatrons.find((x) => x.id === patronId)!.anon || rand() < 0.15;
    }
    used.add(patronId);

    const giftId = `gft_seed_${String(++giftSeq).padStart(4, "0")}`;
    const span = Math.max(DAY, NOW - createdAt - 2 * 60 * 60 * 1000);
    const at = createdAt + Math.floor(((i + rand()) / amounts.length) * span);
    giftRows.push({
      id: giftId,
      request_id: s.requestId,
      patron_id: patronId,
      amount_cents: amount,
      kind: s.fullyFund && isLast ? "clear" : "give",
      anonymous: anon,
      status: "settled",
      payment_ref: `demo_${giftId}`,
      created_at: at,
    });
    if (patronId.startsWith("usr_demo_")) {
      const log = demoGiftLog.get(patronId) ?? [];
      log.push({ giftId, requestCreated: createdAt });
      demoGiftLog.set(patronId, log);
    }
    funded += amount;
  });

  const fullyFunded = funded >= goal;
  sql.push(
    insert("requests", {
      id: s.requestId,
      seeker_id: s.userId,
      first_name: s.firstName,
      age: s.age,
      city: s.city,
      country: s.country,
      country_code: s.countryCode,
      lat: s.lat,
      lng: s.lng,
      category: s.category,
      headline: s.headline,
      story: s.story,
      breakdown: JSON.stringify(s.breakdown),
      goal_cents: goal,
      funded_cents: funded,
      gift_count: amounts.length,
      status: fullyFunded ? "funded" : "active",
      verification: s.verified ? "verified" : "unverified",
      verification_at: null,
      avatar_seed: `${s.firstName}-${s.slug}`,
      photo_key: null,
      blur_photo: false,
      is_demo: true,
      created_at: createdAt,
      funded_at: fullyFunded ? NOW - Math.floor(rand() * 10 + 1) * DAY : null,
    }),
  );

  s.updates.forEach((u, i) => {
    sql.push(
      insert("request_updates", {
        id: `upd_seed_${s.slug.replace(/-/g, "_")}_${i}`,
        request_id: s.requestId,
        kind: u.kind,
        body: u.body,
        created_at: NOW - u.daysAgo * DAY - Math.floor(rand() * 10) * 60 * 60 * 1000,
      }),
    );
  });
}

// Spread demo Patrons' most recent gifts one per week so their giving streaks look real.
for (const log of demoGiftLog.values()) {
  const rows = log
    .map((l) => giftRows.find((g) => g.id === l.giftId)!)
    .sort((a, b) => (b.created_at as number) - (a.created_at as number));
  rows.slice(0, 7).forEach((g, w) => {
    const requestCreated = log.find((l) => l.giftId === g.id)!.requestCreated;
    const candidate = NOW - w * 7 * DAY - Math.floor(rand() * 3 * DAY) - 2 * 60 * 60 * 1000;
    if (candidate > requestCreated) g.created_at = candidate;
  });
}

for (const g of giftRows) {
  sql.push(insert("gifts", g));
  const patronAcct = `patron:${g.patron_id}`;
  const requestAcct = `request:${g.request_id}`;
  const amt = g.amount_cents as number;
  sql.push(
    insert("ledger_entries", { id: `${g.id}:p`, gift_id: g.id, account: patronAcct, delta_cents: -amt, memo: "gift", created_at: g.created_at }),
    insert("ledger_entries", { id: `${g.id}:r`, gift_id: g.id, account: requestAcct, delta_cents: amt, memo: "gift", created_at: g.created_at }),
  );
  addBalance(patronAcct, -amt);
  addBalance(requestAcct, amt);
}
for (const [account, cents] of balances) {
  sql.push(insert("balances", { account, balance_cents: cents, updated_at: NOW }));
}

mkdirSync(".wrangler", { recursive: true });
writeFileSync(".wrangler/seed.sql", sql.join("\n") + "\n");
console.log(
  `Seed written: ${seekers.length} requests, ${giftRows.length} gifts, ${allPatrons.length} patrons → .wrangler/seed.sql`,
);
